import { useSettings, type PluginSurfaceProps } from "@getpaseo/plugin/client";
import { Pressable, ScrollView, Text } from "react-native";
import { followUpSettings, MODEL } from "../shared/contracts";

export function SettingsScreen(props: PluginSurfaceProps & { supported: boolean }) {
  const settings = useSettings(followUpSettings);
  return (
    <ScrollView
      style={{ backgroundColor: props.theme.colors.surface0 }}
      contentContainerStyle={{ padding: 24, gap: 16 }}
    >
      <Text style={{ color: props.theme.colors.foreground, fontSize: 20 }}>
        Follow-up suggestions
      </Text>
      <Text style={{ color: props.theme.colors.foreground }}>
        Settings apply to {props.host.label}. When enabled, open agent chats can make extra {MODEL}{" "}
        calls using this host's saved Codex login. Each completed turn is attempted once, with at
        most eight recent text messages (12,000 characters). No tools or automatic submission.
      </Text>
      {!props.supported && (
        <Text style={{ color: props.theme.colors.foreground }}>
          This client does not support keyboard composer suggestions. No suggestions will be
          generated by this client.
        </Text>
      )}
      {settings.status === "ready" && (
        <Pressable
          accessibilityRole="switch"
          accessibilityState={{ checked: settings.values.enabled, disabled: settings.saving }}
          disabled={settings.saving}
          onPress={() =>
            void settings.save({ enabled: !settings.values.enabled }, settings.revision)
          }
        >
          <Text style={{ color: props.theme.colors.foreground }}>
            {settings.saving
              ? "Saving…"
              : settings.values.enabled
                ? "Disable suggestions"
                : "Enable suggestions"}
          </Text>
        </Pressable>
      )}
      {settings.status === "loading" && (
        <Text style={{ color: props.theme.colors.foreground }}>Loading…</Text>
      )}
      {(settings.status === "error" || settings.status === "invalid") && (
        <>
          <Text style={{ color: props.theme.colors.foreground }}>
            Could not load Follow-up settings.
          </Text>
          <Pressable onPress={() => void settings.reload()}>
            <Text style={{ color: props.theme.colors.foreground }}>Reload settings</Text>
          </Pressable>
          {settings.status === "invalid" && (
            <Pressable onPress={() => void settings.reset()}>
              <Text style={{ color: props.theme.colors.foreground }}>Reset settings</Text>
            </Pressable>
          )}
        </>
      )}
      {settings.saveError && (
        <Text style={{ color: props.theme.colors.foreground }}>
          Could not save settings. Reload and try again.
        </Text>
      )}
      <Text style={{ color: props.theme.colors.foreground }}>
        If Luna is unavailable, check the saved Codex login, gpt-6-luna access and the local model
        catalogue on this host. The CLI must support the isolated tool-free invocation; no
        alternative model is used.
      </Text>
      <Text style={{ color: props.theme.colors.foreground }}>
        Tab or Right Arrow accepts the faint suggestion as an editable draft. Escape or typing
        dismisses it. Touch acceptance is not currently supported by Paseo Max; mobile clients do
        not generate suggestions. Historical replies are not backfilled when the plugin starts.
      </Text>
    </ScrollView>
  );
}
